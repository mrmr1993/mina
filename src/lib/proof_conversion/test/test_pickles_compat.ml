(* Main: run all tests                                                 *)
(* ------------------------------------------------------------------ *)

let check_vk ~name ~expected ~actual =
  let hash_str = Kimchi_pasta.Pasta.Fp.to_string actual in
  printf "  VK hash (OCaml):  %s\n" hash_str ;
  printf "  VK hash (o1js):   %s\n" expected ;
  if String.equal hash_str expected then (printf "  PASS\n" ; true)
  else (
    printf "  FAIL - VK hashes differ\n" ;
    ignore name ;
    false )

let () =
  let expected_simple_vk_hash =
    "28164523456835703146609862384240602928554830215542611547995955594202748290944"
  in
  let expected_recursive_vk_hash =
    "3247524153122767581645069378962115724676436734987413176127638916743756576935"
  in
  let all_pass = ref true in

  printf "Pickles o1js compatibility test\n" ;
  printf "================================\n" ;

  (* --- Simple program (N0) --- *)
  printf "\n[simple-compat-test]\n" ;
  printf "  Compiling... %!" ;
  let simple_hash = compile_simple ~name:"simple-compat-test" in
  printf "done\n" ;
  if
    not
      (check_vk ~name:"simple" ~expected:expected_simple_vk_hash
         ~actual:simple_hash )
  then all_pass := false ;

  (* --- Recursive program (N1) --- *)
  ( match Stdlib.Sys.getenv_opt "SKIP_RECURSIVE" with
  | Some _ ->
      printf "\n[recursive-compat-test] SKIPPED (SKIP_RECURSIVE set)\n"
  | None ->
      printf "\n[recursive-compat-test]\n" ;
      printf "  Compiling... %!" ;
      let recursive_hash = compile_recursive ~name:"recursive-compat-test" in
      printf "done\n" ;
      if
        not
          (check_vk ~name:"recursive" ~expected:expected_recursive_vk_hash
             ~actual:recursive_hash )
      then all_pass := false ) ;

  if not !all_pass then (printf "\nFAILED\n" ; exit 1)
  else printf "\nAll compatibility checks passed.\n"
