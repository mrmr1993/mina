#!/usr/bin/env python3
"""Regenerate RESULTS.md from results.jsonl, sorted by makespan (fastest first).

Each row in results.jsonl is one bench.sh run. OOM / failed runs sort to the
bottom. The markdown is a generated artifact -- edit results.jsonl (or re-run
bench.sh), never RESULTS.md directly, except the prose sections below the table
which are preserved across regenerations via the FINDINGS marker.
"""
import json, os, sys, statistics

here = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
jsonl = os.path.join(here, "results.jsonl")
md = os.path.join(here, "RESULTS.md")

rows = []
if os.path.exists(jsonl):
    for line in open(jsonl):
        line = line.strip()
        if line:
            rows.append(json.loads(line))


def med(xs):
    return statistics.median(xs) if xs else None


def sortkey(r):
    times = r.get("makespan_s") or []
    if r.get("oom") or not times:
        return (1, 1e9)
    return (0, med(times))


rows.sort(key=sortkey)

HDR = "| makespan (s) | cores | peak RAM | minAvail | config | slots | env | commit (main/sub) | date | vk | note |"
SEP = "|---:|---:|---:|---:|---|---:|---|---|---|---|---|"
lines = [
    "# Nori proof-conversion benchmark results",
    "",
    "Generated by `gen_results.py` from `results.jsonl`. **Do not edit the table",
    "by hand** -- run `scripts/nori_bench/bench.sh` (it appends + regenerates).",
    "Sorted fastest-first; OOM/failed runs at the bottom. Target makespan ~105s.",
    "",
    HDR, SEP,
]
for r in rows:
    times = r.get("makespan_s") or []
    if r.get("oom") or not times:
        msp = "**OOM**" if r.get("oom") else "fail"
    else:
        mn, md_ = min(times), med(times)
        msp = f"{md_:g}" if mn == max(times) else f"{mn:g}–{max(times):g} (med {md_:g})"
    cores = r.get("cores") or []
    cores = f"{statistics.mean(cores):.1f}" if cores else "-"
    peak = f"{r.get('peak_ram_gb','?')} GB"
    avail = f"{r['min_memavail_mb']/1024:.1f} GB" if r.get("min_memavail_mb") else "-"
    pools = "<br>".join(r.get("pools", []))
    commit = f"{r.get('commit_main','?')}/{r.get('commit_sub','?')}"
    if r.get("dirty"):
        commit += f" ⚠{r['dirty']}"
    vk = {"true": "✓", "false": "✗"}.get(str(r.get("vk_match")), "?")
    note = r.get("note", "") or ""
    lines.append(
        f"| {msp} | {cores} | {peak} | {avail} | **{r.get('name','?')}**<br>{pools} "
        f"| {r.get('slots','?')} | {r.get('env','') or '-'} | {commit} | {r.get('date','?')} | {vk} | {note} |"
    )

# Preserve any prose after the FINDINGS marker across regenerations.
MARK = "<!-- FINDINGS -->"
findings = ""
if os.path.exists(md):
    txt = open(md).read()
    if MARK in txt:
        findings = txt[txt.index(MARK):]
if not findings:
    findings = MARK + "\n\n## Findings / dead ends\n\n_(prose below is preserved across regenerations; edit freely)_\n"

open(md, "w").write("\n".join(lines) + "\n\n" + findings)
print(f"wrote {md} ({len(rows)} runs)")
